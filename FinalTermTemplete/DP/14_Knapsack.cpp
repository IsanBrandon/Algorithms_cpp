#include <iostream>
#include <fstream>
#include <vector>
#include <algorithm>

using namespace std;

// input1.txt 파일에서 입력을 받기 위한 파일 입력 스트림
ifstream fin("input1.txt");

/***********************************************************************
 * 0/1 Knapsack
 *
 * 목적:
 * - 배낭 용량 W를 넘지 않으면서
 *   얻을 수 있는 최대 가치를 구한다.
 *
 * 조건:
 * - 각 물건은 최대 한 번만 선택 가능
 *
 * DP 정의:
 *
 * dp[i][cap]
 *
 * = 앞의 i개 물건만 고려했을 때
 *   배낭 용량 cap으로 얻을 수 있는 최대 가치
 *
 * 점화식:
 *
 * 물건 i를 사용하지 않는 경우
 *
 * dp[i][cap] = dp[i-1][cap]
 *
 * 물건 i를 사용하는 경우
 *
 * dp[i][cap]
 * =
 * max(
 *      dp[i-1][cap],
 *      dp[i-1][cap-w[i]] + v[i]
 *    )
 *
 * 시간복잡도:
 * O(nW)
 ***********************************************************************/
int knapsack(vector<int> &w,
             vector<int> &v,
             int W)
{
    int n = w.size();

    /*
     * dp[i][cap]
     *
     * i개 물건 사용 가능
     * 현재 용량 cap
     */
    vector<vector<int>> dp(
        n + 1,
        vector<int>(W + 1, 0)
    );

    /*
     * i = 사용 가능한 물건 개수
     */
    for (int i = 1; i <= n; i++) {

        /*
         * cap = 현재 배낭 용량
         */
        for (int cap = 0; cap <= W; cap++) {

            /***********************************************************
             * 경우 1
             *
             * 현재 물건을 선택하지 않음
             ***********************************************************/
            dp[i][cap] = dp[i - 1][cap];

            /***********************************************************
             * 경우 2
             *
             * 현재 물건을 선택
             *
             * 단, 현재 물건 무게를 담을 수 있어야 함
             ***********************************************************/
            if (cap >= w[i - 1]) {

                dp[i][cap] = max(
                    dp[i][cap],

                    dp[i - 1][cap - w[i - 1]]
                    + v[i - 1]
                );
            }
        }
    }

    /*
     * 모든 물건 고려
     * 배낭 용량 W
     */
    return dp[n][W];
}

int main()
{
    /*******************************************************************
     * 파일 열기 확인
     *******************************************************************/
    if (!fin) {

        cout << "Cannot open input1.txt\n";

        return 0;
    }

    int n;
    int W;

    /*
     * n = 물건 개수
     * W = 배낭 용량
     */
    fin >> n >> W;

    vector<int> w(n);
    vector<int> v(n);

    /*
     * 물건 입력
     *
     * wi vi
     */
    for (int i = 0; i < n; i++) {

        fin >> w[i] >> v[i];
    }

    /*
     * 최대 가치 출력
     */
    cout << knapsack(w, v, W) << "\n";

    fin.close();

    return 0;
}