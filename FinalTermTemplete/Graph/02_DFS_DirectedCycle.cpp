#include <iostream>
#include <fstream>
#include <vector>

using namespace std;

ifstream fin("input1.txt");

/***********************************************************************
 * DFS를 이용한 방향 그래프 사이클 탐색
 *
 * color 배열 의미:
 *
 * 0 = 아직 방문하지 않음 (WHITE)
 * 1 = 현재 DFS 탐색 중 (GRAY)
 * 2 = 탐색 완료 (BLACK)
 *
 * 핵심 아이디어:
 *
 * DFS를 수행하다가
 * 현재 탐색 경로에 포함된 정점(GRAY)을 다시 만나면
 * 방향 사이클이 존재한다.
 *
 * 예:
 *
 * 0 → 1 → 2 → 3
 *     ↑       ↓
 *     └───────┘
 *
 * DFS가 1 → 2 → 3 으로 진행 중일 때
 * 3에서 다시 1(GRAY)을 만나면 사이클 발견
 ***********************************************************************/
bool dfsCycleDirected(int u,
                      vector<vector<int>> &adj,
                      vector<int> &color)
{
    // 현재 정점 u를 탐색 중(GRAY) 상태로 표시
    color[u] = 1;

    // u와 연결된 모든 정점 검사
    for (int v : adj[u]) {

        /***************************************************************
         * GRAY 정점을 다시 만났다면?
         *
         * 현재 DFS 경로에 포함된 정점을 다시 방문했다는 뜻
         *
         * => Back Edge 발견
         * => 방향 사이클 존재
         ***************************************************************/
        if (color[v] == 1)
            return true;

        /***************************************************************
         * 아직 방문하지 않은 정점이라면 DFS 계속 수행
         ***************************************************************/
        if (color[v] == 0) {

            if (dfsCycleDirected(v, adj, color))
                return true;
        }
    }

    /***************************************************************
     * u에서 출발하는 모든 탐색이 끝났으므로
     * BLACK 상태로 변경
     ***************************************************************/
    color[u] = 2;

    return false;
}

/***********************************************************************
 * 방향 그래프 입력 함수
 *
 * input1.txt 예시:
 *
 * 4 4
 * 0 1
 * 1 2
 * 2 3
 * 3 1
 *
 * 의미:
 *
 * 정점 수 = 4
 * 간선 수 = 4
 *
 * 0 → 1
 * 1 → 2
 * 2 → 3
 * 3 → 1
 ***********************************************************************/
void inputDirectedGraph(int &n,
                        int &m,
                        vector<vector<int>> &adj)
{
    // 정점 수, 간선 수 입력
    fin >> n >> m;

    // 인접 리스트 생성
    adj.assign(n, vector<int>()); // adj를 크기 n짜리 vector로 새로 만들고, 각 칸에는 빈 vector<int>를 넣어라.
    // ex. n=3이면 adj는 [ [], [], [] ] 형태가 된다. -> adj[0], adj[1], adj[2]는 모두 빈 vector<int>이다.


    // 간선 입력
    for (int i = 0; i < m; i++) {

        int u, v;

        fin >> u >> v;

        /***************************************************************
         * 방향 그래프
         *
         * u → v
         *
         * 만 저장
         ***************************************************************/
        adj[u].push_back(v);
    }
}

/***********************************************************************
 * 그래프 전체에 대해 사이클 검사
 *
 * 왜 모든 정점을 시작점으로 확인해야 하는가?
 *
 * 예:
 *
 * 0 → 1
 *
 * 2 → 3 → 4
 * ↑       ↓
 * └───────┘
 *
 * DFS를 0부터만 시작하면
 * 2,3,4에 있는 사이클을 발견할 수 없음.
 *
 * 따라서 모든 정점에 대해 DFS 시작 가능성을 검사해야 함.
 ***********************************************************************/
bool hasCycleDirected(vector<vector<int>> &adj)
{
    int n = adj.size();

    /***************************************************************
     * 초기 상태:
     * 모든 정점은 WHITE(0)
     ***************************************************************/
    vector<int> color(n, 0);

    for (int i = 0; i < n; i++) {

        // 아직 방문하지 않은 정점이면 DFS 시작
        if (color[i] == 0) {

            if (dfsCycleDirected(i, adj, color))
                return true;
        }
    }

    return false;
}

int main()
{
    if (!fin) {
        cout << "Cannot open input1.txt\n";
        return 0;
    }

    int n;
    int m;

    vector<vector<int>> adj;

    /***************************************************************
     * 방향 그래프 입력
     ***************************************************************/
    inputDirectedGraph(n, m, adj);


    if (hasCycleDirected(adj)) {
        cout << "YES\n";
    } else {
        cout << "NO\n";
    }

    fin.close();

    return 0;
}